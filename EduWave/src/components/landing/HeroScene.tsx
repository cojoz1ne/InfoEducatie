"use client";

import React, { useRef, useMemo, useEffect } from "react";
import { Canvas, useFrame, useThree } from "@react-three/fiber";
import * as THREE from "three";
import styles from "./HeroScene.module.css";

// 1. Shaders for the Interactive Wave Surface
const waveVertexShader = `
  uniform float uTime;
  uniform vec2 uMouse;
  uniform float uMouseStrength;

  varying vec2 vUv;
  varying vec3 vNormal;
  varying vec3 vPosition;
  varying float vElevation;
  varying float vMouseDist;

  // Calculate wave height using a sum of sine waves (Gerstner-like combination)
  float getWaveHeight(vec2 pos, float time) {
    float height = 0.0;
    
    // Primary deep wave
    vec2 d1 = normalize(vec2(1.0, 0.4));
    float w1 = 0.25; // spatial frequency
    float a1 = 0.16; // amplitude
    float s1 = 0.5;  // speed/temporal frequency
    height += sin(dot(d1, pos) * w1 - time * s1) * a1;
    
    // Secondary diagonal wave
    vec2 d2 = normalize(vec2(-0.7, 0.8));
    float w2 = 0.55;
    float a2 = 0.08;
    float s2 = 0.8;
    height += cos(dot(d2, pos) * w2 - time * s2) * a2;
    
    // High frequency ripples
    vec2 d3 = normalize(vec2(0.2, -1.0));
    float w3 = 1.1;
    float a3 = 0.03;
    float s3 = 1.2;
    height += sin(dot(d3, pos) * w3 - time * s3) * a3;
    
    return height;
  }

  // Calculate the ripple generated by mouse interaction
  float getMouseRipple(vec2 pos, float time, vec2 mousePos, float strength) {
    if (strength < 0.001) return 0.0;
    
    float dist = distance(pos, mousePos);
    
    // Wider, smoother ripple wave settings
    float frequency = 2.2;
    float speed = 4.0;
    float decay = 0.6; // attenuation factor
    
    float ripple = sin(dist * frequency - time * speed) * 0.14 * strength;
    
    // Smooth out the sharp spike directly under the cursor
    float centerDampen = smoothstep(0.0, 1.2, dist);
    
    // Apply center dampening and exponential decay
    return ripple * centerDampen * exp(-dist * decay);
  }

  void main() {
    vUv = uv;
    vec3 pos = position;
    
    // Calculate total vertical height (z coordinate in local plane)
    float baseH = getWaveHeight(pos.xy, uTime);
    float rippleH = getMouseRipple(pos.xy, uTime, uMouse, uMouseStrength);
    
    pos.z = baseH + rippleH;
    
    // Pass properties to fragment shader
    vElevation = pos.z;
    vPosition = (modelMatrix * vec4(pos, 1.0)).xyz;
    vMouseDist = distance(pos.xy, uMouse);
    
    // Estimate normal vector using finite differences
    float eps = 0.05;
    float hL = getWaveHeight(pos.xy - vec2(eps, 0.0), uTime) + getMouseRipple(pos.xy - vec2(eps, 0.0), uTime, uMouse, uMouseStrength);
    float hR = getWaveHeight(pos.xy + vec2(eps, 0.0), uTime) + getMouseRipple(pos.xy + vec2(eps, 0.0), uTime, uMouse, uMouseStrength);
    float hD = getWaveHeight(pos.xy - vec2(0.0, eps), uTime) + getMouseRipple(pos.xy - vec2(0.0, eps), uTime, uMouse, uMouseStrength);
    float hU = getWaveHeight(pos.xy + vec2(0.0, eps), uTime) + getMouseRipple(pos.xy + vec2(0.0, eps), uTime, uMouse, uMouseStrength);
    
    vec3 tangent = normalize(vec3(eps * 2.0, 0.0, hR - hL));
    vec3 bitangent = normalize(vec3(0.0, eps * 2.0, hU - hD));
    vec3 normal = normalize(cross(tangent, bitangent));
    
    vNormal = normalize(normalMatrix * normal);
    
    gl_Position = projectionMatrix * modelViewMatrix * vec4(pos, 1.0);
  }
`;

const waveFragmentShader = `
  uniform float uTime;
  uniform vec3 uColorLow;
  uniform vec3 uColorHigh;
  uniform vec3 uColorGlow;
  uniform float uMouseStrength;

  varying vec2 vUv;
  varying vec3 vNormal;
  varying vec3 vPosition;
  varying float vElevation;
  varying float vMouseDist;

  void main() {
    vec3 normal = normalize(vNormal);
    
    // 1. Base color gradient from wave height (deeper parts are darker, crests are bright)
    float heightFactor = clamp((vElevation + 0.6) / 1.2, 0.0, 1.0);
    vec3 baseColor = mix(uColorLow, uColorHigh, heightFactor);
    
    // 2. Specular Highlights (Blinn-Phong)
    vec3 lightDir = normalize(vec3(5.0, 5.0, 10.0));
    vec3 viewDir = normalize(cameraPosition - vPosition);
    vec3 halfDir = normalize(lightDir + viewDir);
    
    float specular = pow(max(dot(normal, halfDir), 0.0), 32.0);
    vec3 specColor = vec3(0.5, 0.9, 1.0) * specular * 0.4;
    
    // 3. Fresnel reflection effect for the glassmorphism edge highlights
    float fresnel = pow(1.0 - max(dot(normal, viewDir), 0.0), 4.0);
    vec3 fresnelColor = mix(uColorHigh, vec3(1.0), 0.4) * fresnel * 0.9;
    
    // 4. Bioluminescent Mouse Glow
    float glowRadius = 3.0;
    float glowIntensity = exp(-vMouseDist * 0.85) * (0.2 + uMouseStrength * 0.5);
    vec3 glowColor = uColorGlow * glowIntensity * 0.4;
    
    // 5. Procedural Cyber Grid Lines
    float gridDensity = 45.0;
    vec2 gridUv = vUv * gridDensity;
    vec2 gridDeriv = fwidth(gridUv);
    vec2 gridVal = abs(fract(gridUv - 0.5) - 0.5) / gridDeriv;
    float lineVal = min(gridVal.x, gridVal.y);
    float gridLines = 1.0 - min(lineVal, 1.0);
    
    // Fade grid in the distance for better depth perspective
    float viewDist = length(cameraPosition - vPosition);
    float gridFade = clamp(1.0 - (viewDist - 3.0) / 16.0, 0.0, 1.0);
    
    // Combine grid and mouse glow for interactive wireframe highlights
    vec3 gridFinalColor = uColorGlow * gridLines * gridFade * 0.08;
    gridFinalColor += uColorGlow * gridLines * gridFade * glowIntensity * 0.4;
    
    // 6. Output Color Composite
    vec3 finalColor = baseColor + specColor + fresnelColor + glowColor + gridFinalColor;
    
    // Opacity with Fresnel shimmer
    float opacity = mix(0.3, 0.85, fresnel);
    opacity = clamp(opacity + glowIntensity * 0.15 + gridLines * 0.08, 0.0, 0.9);
    
    gl_FragColor = vec4(finalColor, opacity);
  }
`;

// 2. Shaders for the Floating Particles (synchronized with the wave surface)
const particleVertexShader = `
  uniform float uTime;
  uniform vec2 uMouse;
  uniform float uMouseStrength;
  uniform float uPixelRatio;

  varying float vElevation;
  varying float vMouseDist;

  // Wave height matching the wave plane
  float getWaveHeight(vec2 pos, float time) {
    float height = 0.0;
    
    vec2 d1 = normalize(vec2(1.0, 0.4));
    float w1 = 0.25;
    float a1 = 0.16;
    float s1 = 0.5;
    height += sin(dot(d1, pos) * w1 - time * s1) * a1;
    
    vec2 d2 = normalize(vec2(-0.7, 0.8));
    float w2 = 0.55;
    float a2 = 0.08;
    float s2 = 0.8;
    height += cos(dot(d2, pos) * w2 - time * s2) * a2;
    
    vec2 d3 = normalize(vec2(0.2, -1.0));
    float w3 = 1.1;
    float a3 = 0.03;
    float s3 = 1.2;
    height += sin(dot(d3, pos) * w3 - time * s3) * a3;
    
    return height;
  }

  float getMouseRipple(vec2 pos, float time, vec2 mousePos, float strength) {
    if (strength < 0.001) return 0.0;
    float dist = distance(pos, mousePos);
    float frequency = 2.2;
    float speed = 4.0;
    float decay = 0.6;
    float ripple = sin(dist * frequency - time * speed) * 0.14 * strength;
    float centerDampen = smoothstep(0.0, 1.2, dist);
    return ripple * centerDampen * exp(-dist * decay);
  }

  void main() {
    vec3 pos = position;
    
    float waveH = getWaveHeight(pos.xy, uTime);
    float rippleH = getMouseRipple(pos.xy, uTime, uMouse, uMouseStrength);
    
    // Float particles slightly above the mesh to avoid intersections
    pos.z = waveH + rippleH + 0.08;
    
    vElevation = pos.z;
    vMouseDist = distance(pos.xy, uMouse);
    
    vec4 mvPosition = modelViewMatrix * vec4(pos, 1.0);
    gl_Position = projectionMatrix * mvPosition;
    
    // Size attenuation based on depth and monitor pixel ratio
    float baseSize = 0.065;
    gl_PointSize = baseSize * (350.0 / -mvPosition.z) * uPixelRatio;
  }
`;

const particleFragmentShader = `
  uniform vec3 uColorGlow;
  uniform float uMouseStrength;

  varying float vElevation;
  varying float vMouseDist;

  void main() {
    // Circle shaping
    vec2 coord = gl_PointCoord - vec2(0.5);
    if (length(coord) > 0.5) discard;
    
    // Bright glow when mouse is near
    float glowIntensity = exp(-vMouseDist * 0.6) * (0.15 + uMouseStrength * 0.85);
    vec3 particleColor = mix(vec3(0.0, 0.7, 1.0), uColorGlow, glowIntensity);
    
    // Smooth circle anti-aliasing
    float alpha = 1.0 - smoothstep(0.25, 0.5, length(coord));
    
    gl_FragColor = vec4(particleColor, alpha * 0.8);
  }
`;

// 3. Combined Interactive Wave + Particle Component
function InteractiveOcean() {
  const meshRef = useRef<THREE.Mesh>(null);
  const oceanMaterialRef = useRef<THREE.ShaderMaterial>(null);
  const particleMaterialRef = useRef<THREE.ShaderMaterial>(null);
  const targetMouse = useRef(new THREE.Vector2(0, 0));
  const globalMouse = useRef(new THREE.Vector2(0, 0));
  const targetStrength = useRef(0.0);

  // Create shared uniforms memoized for performance
  const uniforms = useMemo(() => ({
    uTime: { value: 0 },
    uMouse: { value: new THREE.Vector2(0, 0) },
    uMouseStrength: { value: 0.0 },
    uColorLow: { value: new THREE.Color("#070d19") },  // Deep dark blue
    uColorHigh: { value: new THREE.Color("#0077b6") }, // Wave blue
    uColorGlow: { value: new THREE.Color("#00f5d4") }, // Bioluminescent Teal
    uPixelRatio: { value: 1.0 }
  }), []);

  // Update pixel ratio on client mount
  useEffect(() => {
    if (typeof window !== "undefined") {
      uniforms.uPixelRatio.value = Math.min(window.devicePixelRatio, 2.0);
    }
  }, [uniforms]);

  // Bind global pointer move listener to capture mouse positions even above UI overlays
  useEffect(() => {
    const handleGlobalPointerMove = (e: PointerEvent) => {
      if (typeof window !== "undefined") {
        const x = (e.clientX / window.innerWidth) * 2 - 1;
        const y = -(e.clientY / window.innerHeight) * 2 + 1;
        globalMouse.current.set(x, y);
      }
    };
    window.addEventListener("pointermove", handleGlobalPointerMove);
    return () => window.removeEventListener("pointermove", handleGlobalPointerMove);
  }, []);

  const handlePointerDown = (e: any) => {
    if (!meshRef.current) return;
    // Strong impact ripple on click (toned down)
    targetStrength.current = 1.8;
  };

  // Particles buffer setup
  const particleCount = 2000;
  const particlePositions = useMemo(() => {
    const arr = new Float32Array(particleCount * 3);
    for (let i = 0; i < particleCount; i++) {
      arr[i * 3] = (Math.random() - 0.5) * 75;     // X local coordinate
      arr[i * 3 + 1] = (Math.random() - 0.5) * 55; // Y local coordinate
      arr[i * 3 + 2] = 0.0;                        // Z calculated in shader
    }
    return arr;
  }, []);

  useFrame((state) => {
    const time = state.clock.getElapsedTime();

    // Project global screen mouse coordinates onto our wave mesh using R3F raycaster
    state.raycaster.setFromCamera(globalMouse.current, state.camera);
    if (meshRef.current) {
      const intersects = state.raycaster.intersectObject(meshRef.current);
      if (intersects.length > 0) {
        const localPoint = meshRef.current.worldToLocal(intersects[0].point.clone());
        targetMouse.current.set(localPoint.x, localPoint.y);
        targetStrength.current = 1.1; // active hover
      }
    }

    // Butttery smooth interpolation of mouse position and ripple strength
    uniforms.uMouse.value.x += (targetMouse.current.x - uniforms.uMouse.value.x) * 0.08;
    uniforms.uMouse.value.y += (targetMouse.current.y - uniforms.uMouse.value.y) * 0.08;

    // Slow decay of interaction strength to return waves to normal state
    targetStrength.current *= 0.965;
    uniforms.uMouseStrength.value += (targetStrength.current - uniforms.uMouseStrength.value) * 0.08;

    // Mutate shader uniforms directly on the materials for 100% reliable animation
    if (oceanMaterialRef.current) {
      oceanMaterialRef.current.uniforms.uTime.value = time;
      oceanMaterialRef.current.uniforms.uMouse.value.copy(uniforms.uMouse.value);
      oceanMaterialRef.current.uniforms.uMouseStrength.value = uniforms.uMouseStrength.value;
    }
    if (particleMaterialRef.current) {
      particleMaterialRef.current.uniforms.uTime.value = time;
      particleMaterialRef.current.uniforms.uMouse.value.copy(uniforms.uMouse.value);
      particleMaterialRef.current.uniforms.uMouseStrength.value = uniforms.uMouseStrength.value;
    }

    // Keep uniforms object in sync
    uniforms.uTime.value = time;
  });

  return (
    <group position={[0, -2.1, -1.0]} rotation={[-Math.PI / 2.15, 0, 0]}>
      {/* 1. Main Wave Plane Mesh */}
      <mesh
        ref={meshRef}
        onPointerDown={handlePointerDown}
      >
        <planeGeometry args={[75, 55, 340, 240]} />
        <shaderMaterial
          ref={oceanMaterialRef}
          vertexShader={waveVertexShader}
          fragmentShader={waveFragmentShader}
          uniforms={uniforms}
          transparent={true}
          depthWrite={true}
          side={THREE.DoubleSide}
        />
      </mesh>

      {/* 2. Floating Bioluminescent Particles */}
      <points>
        <bufferGeometry>
          <bufferAttribute
            attach="attributes-position"
            args={[particlePositions, 3]}
          />
        </bufferGeometry>
        <shaderMaterial
          ref={particleMaterialRef}
          vertexShader={particleVertexShader}
          fragmentShader={particleFragmentShader}
          uniforms={uniforms}
          transparent={true}
          depthWrite={false}
          blending={THREE.AdditiveBlending}
        />
      </points>
    </group>
  );
}

// 5. Main Hero Scene Canvas Wrapper
export default function HeroScene() {
  return (
    <div className={styles.canvasContainer}>
      <Canvas camera={{ position: [0, 0, 5], fov: 58 }} frameloop="always">
        <ambientLight intensity={0.5} />
        <directionalLight position={[5, 10, 6]} intensity={1.8} color="#00b4d8" />
        <pointLight position={[-8, -5, -3]} intensity={1.4} color="#00f5d4" />
        <InteractiveOcean />
      </Canvas>
    </div>
  );
}



